// @vitest-environment node
import { toSeedRows } from '@/fixtures/pipodesk/dataset'

const raw = (overrides: Record<string, unknown> = {}) => ({
  id: 'ticket-1',
  enrollmentId: 'enr-1',
  companyId: 'company-1',
  status: 'broker-processing',
  subject: 'SulAmérica · Saúde · Ana',
  beneficiaryName: 'Ana',
  taxId: null,
  companyName: 'Caiçara',
  porte: 'medio',
  carrierId: 'sulamerica',
  carrierName: 'SulAmérica',
  product: 'health',
  enrollmentType: 'inclusion',
  contractType: 'clt',
  vinculo: 'titular',
  assigneeId: 'user-15',
  groupId: 'pod-5',
  priority: null,
  actionDate: null,
  tags: [],
  sourceSystem: 'enrollment-integrations',
  createdAt: '2026-08-01T10:00:00.000Z',
  updatedAt: '2026-08-02T10:00:00.000Z',
  closedAt: null,
  ...overrides,
})

/**
 * The loader runs at module scope, so a bad row throws during the import —
 * before React exists, where no error boundary can reach it. The fixture is
 * regenerated by a script in another repo; a vocabulary drift there must not
 * be able to stop the app from booting.
 */
describe('toSeedRows', () => {
  it('should derive display and reason from the API status', () => {
    const [row] = toSeedRows([raw({ status: 'missing-documents' })])

    expect(row.status).toBe('missing-documents')
    expect(row.display).toBe('client-pending')
    expect(row.reason).toBe('missing-documents')
  })

  it('should drop a row whose status is outside the vocabulary, instead of throwing', () => {
    const warn = vi.spyOn(console, 'error').mockImplementation(() => {})

    const rows = toSeedRows([
      raw({ id: 'ticket-ok' }),
      raw({ id: 'ticket-ruim', status: 'em-analise-rh' }),
    ])

    expect(rows.map((row) => row.id)).toEqual(['ticket-ok'])
    // Silence would be worse than the crash: nobody would notice the hole.
    expect(warn).toHaveBeenCalledWith(expect.stringContaining('ticket-ruim'))
    warn.mockRestore()
  })

  it('should default the display number until the export carries one', () => {
    const [row] = toSeedRows([raw()])

    expect(row.displayNumber).toBeNull()
  })
})
