/**
 * The loader runs at module scope, so a bad row throws during the import —
 * before React exists, where no error boundary can reach it. The fixture is
 * regenerated by a script in another repo; a vocabulary drift there must not
 * be able to stop the app from booting.
 */
describe('toSeedRows', () => {
  it('should derive display and reason from the API status', () => {
    const [row] = toSeedRows([raw({ status: 'missing-documents' })])

    expect(row.status).toBe('missing-documents')
    expect(row.display).toBe('client-pending')
    expect(row.reason).toBe('missing-documents')
  })

  it('should drop a row whose status is outside the vocabulary, instead of throwing', () => {
    const warn = vi.spyOn(console, 'error').mockImplementation(() => {})

    const rows = toSeedRows([
      raw({ id: 'ticket-ok' }),
      raw({ id: 'ticket-ruim', status: 'em-analise-rh' }),
    ])

    expect(rows.map((row) => row.id)).toEqual(['ticket-ok'])
    // Silence would be worse than the crash: nobody would notice the hole.
    expect(warn).toHaveBeenCalledWith(expect.stringContaining('ticket-ruim'))
    warn.mockRestore()
  })

  it('should default the display number until the export carries one', () => {
    const [row] = toSeedRows([raw()])

    expect(row.displayNumber).toBeNull()
  })

  /** A key that stops matching yields null, emptying the Vínculo column for
   *  every row — silently, since no other assertion here would notice. */
  it('should translate every relationship the export can write', () => {
    const rows = toSeedRows([
      raw({ id: 'a', vinculo: 'titular' }),
      raw({ id: 'b', vinculo: 'dependente' }),
      raw({ id: 'c', vinculo: 'grupo-familiar' }),
    ])

    expect(rows.map((row) => row.relationship)).toEqual(['holder', 'dependent', 'family-group'])
  })

  it('should null an unknown relationship instead of leaking the raw value', () => {
    const [row] = toSeedRows([raw({ vinculo: 'conjuge' })])

    expect(row.relationship).toBeNull()
  })
})

describe('withoutLegacyPjNull', () => {
  const queue = (contractTypes?: (string | null)[]): Queue => ({
    id: 'queue-pod-1-pj',
    name: 'MOV PJ',
    groupId: 'pod-1',
    ownerId: null,
    subscriberIds: [],
    filter: contractTypes === undefined ? {} : { contractTypes },
    sort: DEFAULT_SORT,
  })

  it('should drop the null that rode along with pj in the prototype', () => {
    expect(withoutLegacyPjNull(queue(['pj', null])).filter.contractTypes).toEqual(['pj'])
  })

  /** `[null]` is a real cut — "no contract in the snapshot". Stripped, it
   *  would be `[]`, which matchesFilter reads as no criterion at all. */
  it('should keep a cut that is only null', () => {
    expect(withoutLegacyPjNull(queue([null])).filter.contractTypes).toEqual([null])
  })

  it('should return the same queue when there is nothing to patch', () => {
    const clt = queue(['clt'])
    const bare = queue()

    expect(withoutLegacyPjNull(clt)).toBe(clt)
    expect(withoutLegacyPjNull(bare)).toBe(bare)
  })
})
